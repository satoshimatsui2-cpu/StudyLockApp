    SHIN("shion", "氷室 シオン", 40),
    LUNA("noa", "如月 ノア", 50),
    LEO("leo", "獅子堂 レオ", 60),
    ARTHUR("allen", "西園寺 アレン", 70),
    HINA("hina", "白河 ヒナ", 80),
