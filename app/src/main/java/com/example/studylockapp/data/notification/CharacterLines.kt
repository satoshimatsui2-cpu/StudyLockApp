    /**
     * 指定されたキャラクターと状況に最適な感情を取得する
     */
    fun getEmotionForContext(character: StudyCharacter, context: NotificationContext): CharacterEmotion {
        // キャラクターごとの特殊な感情表現があればここで分岐
        return when (character) {
            StudyCharacter.ATSUSHI -> when (context) {
                NotificationContext.EVENING_PENDING -> CharacterEmotion.INSPIRE // 赤城 レンなら焦るより鼓舞
                else -> defaultMapping(context)
            }
            StudyCharacter.SHIN -> when (context) {
                NotificationContext.MORNING_MISSED_1 -> CharacterEmotion.ANGER // 氷室 シオンなら照れより怒り（厳しさ）
                else -> defaultMapping(context)
            }
            else -> defaultMapping(context)
        }
    }

    private fun defaultMapping(context: NotificationContext): CharacterEmotion {
        return when (context) {
            NotificationContext.MORNING_NORMAL -> CharacterEmotion.PLEASURE
            NotificationContext.MORNING_STREAK -> CharacterEmotion.JOY
            NotificationContext.MORNING_MISSED_1 -> CharacterEmotion.BLUSH
            NotificationContext.MORNING_MISSED_2 -> CharacterEmotion.SORROW
            NotificationContext.EVENING_PENDING -> CharacterEmotion.PANIC
            NotificationContext.GOAL_COMPLETED -> CharacterEmotion.JOY
            NotificationContext.FRIEND_GOAL_MET -> CharacterEmotion.SURPRISE
        }
    }

    fun getLine(character: StudyCharacter, context: NotificationContext, streak: Int = 0, name: String = "友達"): String {
        val characterLines = lines[character] ?: lines[StudyCharacter.GEORGE]!!
        val contextLines = characterLines[context] ?: characterLines[NotificationContext.MORNING_NORMAL]!!
        val line = contextLines.random()
        
        var formatted = line
        
        try {
            // %s (名前) と %d (数値) の両方または片方に対応
            if (formatted.contains("%s") && formatted.contains("%d")) {
                // String.formatは引数の順序に依存するため、より安全な置換を行う
                formatted = formatted.replace("%s", name).replace("%d", streak.toString())
            } else if (formatted.contains("%s")) {
                formatted = String.format(formatted, name)
            } else if (formatted.contains("%d")) {
                formatted = String.format(formatted, streak)
            }
        } catch (e: Exception) {
            // フォーマットエラー時は原文を返す
        }
        
        // 念のためエスケープされた%を修正
        formatted = formatted.replace("%%", "%")
        
        return formatted
    }
